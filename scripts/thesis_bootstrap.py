#!/usr/bin/env python
"""Paired bootstrap confidence intervals for every reported run.

    python scripts/thesis_bootstrap.py            # -> results/thesis/thesis_cis.md
    python scripts/thesis_bootstrap.py --latex    # the rows the chapter quotes

Items are resampled, and both sides of a comparison are scored on the same draw.
Decoding stochasticity is not captured; read the intervals alongside the run-to-run floor.
"""
import argparse, pathlib, sys
import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import thesis_report as R                                    # noqa: E402

B, SEED = 10000, 0
DOC = R.OUT / "thesis_cis.md"


def ci(a, b, seed=SEED, reps=B):
    """Paired difference b - a in points, with a 95% percentile interval."""
    rng = np.random.default_rng(seed)
    n = len(a)
    idx = rng.integers(0, n, size=(reps, n))
    d = (b[idx].mean(1) - a[idx].mean(1)) * 100
    lo, hi = np.percentile(d, [2.5, 97.5])
    return (b.mean() - a.mean()) * 100, lo, hi


def vec(run, ids, upto=None):
    if upto is None:
        return np.array([run.rec[k]["success"] for k in ids], float)
    return np.array([(run.rec[k].get("solved_at_trial") or 99) <= upto for k in ids], float)



def relevance_rows(bench, actors, runs):
    """Retrieved against random on the same items; the difference is random - retrieved."""
    reg, out = dict(runs), []
    bases = {}
    for k in reg:
        for suf, side in ((", retrieved", "r"), (", random", "x"),
                          (" — retrieved", "r"), (" — random", "x")):
            if k.endswith(suf):
                bases.setdefault(k[:-len(suf)], {})[side] = reg[k]
    for tag, actor in actors:
        for base_label, d in sorted(bases.items()):
            if "r" not in d or "x" not in d:
                continue
            ret, ran = R.Run(d["r"].format(t=tag)), R.Run(d["x"].format(t=tag))
            if not (ret.ok and ran.ok):
                continue
            ids = [k for k in ret.rec if k in ran.rec]
            diff, lo, hi = ci(vec(ret, ids), vec(ran, ids))
            out.append((actor, base_label, len(ids), diff, lo, hi))
    return out


def rows(bench, actors, runs):
    out = []
    for tag, actor in actors:
        base = R.Run(R.BASE[bench].format(t=tag))
        if not base.ok:
            continue
        for label, tmpl in runs:
            run = R.Run(tmpl.format(t=tag))
            if not run.ok:
                continue
            ids = [k for k in base.rec if k in run.rec]
            d, lo, hi = ci(vec(base, ids), vec(run, ids))
            out.append((actor, label, "memoryless baseline", len(ids), d, lo, hi))
        mem, ctl = (R.Run(t.format(t=tag)) for t in R.REFL[bench])
        if mem.ok and ctl.ok:
            ids = [k for k in mem.rec if k in ctl.rec]
            for upto, lab in ((2, "Reflexion @ one reflection"), (None, "Reflexion @ ten trials")):
                d, lo, hi = ci(vec(ctl, ids, upto), vec(mem, ids, upto))
                out.append((actor, lab, "trial-matched control", len(ids), d, lo, hi))
    return out


def main(latex=False):
    body = []
    for bench, actors, runs, name, floor in (
            ("sparc", R.SPARC, R.SPARC_RUNS, "Spatial-Gym", "~3 points"),
            ("stepgame", R.STEP, R.STEP_RUNS, "StepGame", "~3.9 points")):
        body.append(f"\n## {name}\n")
        body.append(f"Run-to-run floor for this benchmark: {floor}. An interval narrower than "
                    f"the floor is not evidence that the difference would survive a re-run.\n")
        body.append("| Actor | Experiment | Against | n | diff | 95% CI |")
        body.append("|---|---|---|---:|---:|---|")
        for actor, label, against, n, d, lo, hi in rows(bench, actors, runs):
            body.append(f"| {actor} | {label} | {against} | {n} | {d:+.1f} | "
                        f"[{lo:+.1f}, {hi:+.1f}] |")
    body.append("\n## Retrieval against random choice\n")
    body.append("Positive numbers favour **random** entries. An interval that straddles zero "
                "says the two cannot be told apart at this sample size.\n")
    body.append("| Benchmark | Actor | Bank | n | random - retrieved | 95% CI |")
    body.append("|---|---|---|---:|---:|---|")
    for bench, actors, runs, name in (("sparc", R.SPARC, R.SPARC_RUNS, "Spatial-Gym"),
                                      ("stepgame", R.STEP, R.STEP_RUNS, "StepGame")):
        for actor, label, n, d, lo, hi in relevance_rows(bench, actors, runs):
            body.append(f"| {name} | {actor} | {label} | {n} | {d:+.1f} | [{lo:+.1f}, {hi:+.1f}] |")

    text = ("# Paired bootstrap confidence intervals\n\n"
            "Generated by `scripts/thesis_bootstrap.py`; do not edit by hand.\n"
            f"{B} resamples of the items, seed {SEED}. Positive numbers favour memory.\n"
            + "\n".join(body) + "\n")
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text(text)
    print(f"wrote {DOC}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--latex", action="store_true")
    main(ap.parse_args().latex)
